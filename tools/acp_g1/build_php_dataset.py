#!/usr/bin/env python3
"""Convert the pinned PHP locomotion examples into an ACP flat-ground dataset.

Only motion/terrain pairs whose released terrain array is empty are selected.
Continuous 4--6 second windows preserve the real stand, turn, and stop frames;
no new trajectory frames or contact labels are invented. Nonempty obstacle
variants remain in the original archive and are recorded as excluded.

Dependencies: numpy, scipy, PyYAML, mujoco. Contact labels must subsequently be
generated by instinct_mj.scripts.acp.label_contacts in the training environment.
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
from pathlib import Path
import subprocess
import tarfile
import urllib.request

import mujoco
import numpy as np
import yaml
from scipy.spatial.transform import Rotation, Slerp


RELEASE_URL = "https://github.com/amazon-far/php_parkour/releases/tag/training-motion-examples-v1"
SOURCE_COMMIT = "6d94161e299e279876f992a298626e47f520cfe3"
ASSET_NAME = "php-motions-locomotion-v1.tar.gz"
ASSET_SHA256 = "2397220209b5ce32cd886340f5b12f62821f17e40bff0d2958b1a70295a08dcf"
ASSET_SIZE = 118303924
ASSET_URL = RELEASE_URL.replace("/tag/", "/download/") + "/" + ASSET_NAME
LICENSE_URL = f"https://raw.githubusercontent.com/amazon-far/php_parkour/{SOURCE_COMMIT}/LICENSE"


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def file_sha(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def fetch_archive(path: Path):
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        temporary = path.with_name(path.name + ".partial")
        with urllib.request.urlopen(ASSET_URL, timeout=60) as response, temporary.open("wb") as handle:
            while block := response.read(1024 * 1024):
                handle.write(block)
        if temporary.stat().st_size != ASSET_SIZE or file_sha(temporary) != ASSET_SHA256:
            raise ValueError("Downloaded PHP archive failed its pinned size/hash check")
        temporary.rename(path)
    if path.stat().st_size != ASSET_SIZE or file_sha(path) != ASSET_SHA256:
        raise ValueError("PHP archive failed its pinned size/hash check")


def write_floor(path: Path):
    """Closed box STL: half extents 14.5,9,.05, top surface exactly z=0."""
    vertices = np.array([[-14.5, -9, -.1], [14.5, -9, -.1], [14.5, 9, -.1], [-14.5, 9, -.1],
                         [-14.5, -9, 0], [14.5, -9, 0], [14.5, 9, 0], [-14.5, 9, 0]], dtype=float)
    faces = [(0, 2, 1), (0, 3, 2), (4, 5, 6), (4, 6, 7), (0, 1, 5), (0, 5, 4),
             (1, 2, 6), (1, 6, 5), (2, 3, 7), (2, 7, 6), (3, 0, 4), (3, 4, 7)]
    lines = ["solid php_flat_ground"]
    for face in faces:
        triangle = vertices[list(face)]
        normal = np.cross(triangle[1] - triangle[0], triangle[2] - triangle[0])
        normal /= np.linalg.norm(normal)
        lines.append(" facet normal " + " ".join(f"{v:.9g}" for v in normal))
        lines.append("  outer loop")
        lines.extend("   vertex " + " ".join(f"{v:.9g}" for v in row) for row in triangle)
        lines.extend(["  endloop", " endfacet"])
    path.write_text("\n".join(lines + ["endsolid php_flat_ground", ""]), encoding="ascii")


def make_model(source: Path):
    xml = source / "src/instinct_mj/assets/resources/acp_g1/g1_29dof.xml"
    # Loading the original XML works with MuJoCo 3.3 and 3.5 and preserves the
    # exact ACP foot capsules. The task's simplified model keeps these feet.
    model = mujoco.MjModel.from_xml_path(str(xml))
    controlled = [i for i in range(model.njnt) if model.jnt_type[i] != mujoco.mjtJoint.mjJNT_FREE]
    names = [model.joint(i).name for i in controlled]
    if len(names) != 23 or any("wrist" in name for name in names):
        raise ValueError("The ACP asset must have 23 non-wrist joints")
    feet = []
    for side in ("left", "right"):
        body = model.body(f"{side}_ankle_roll_link").id
        ids = np.flatnonzero((model.geom_bodyid == body) &
                             (model.geom_type == mujoco.mjtGeom.mjGEOM_CAPSULE) &
                             ((model.geom_contype != 0) | (model.geom_conaffinity != 0)))
        if len(ids) != 7:
            raise ValueError(f"Expected seven ACP {side} foot capsules")
        feet.append(ids)
    return xml, model, names, controlled, feet


def foot_height(model, controlled, feet, pos, quat, joints):
    data = mujoco.MjData(model)
    addresses = [model.jnt_qposadr[i] for i in controlled]
    result = np.empty((len(pos), 2), dtype=np.float64)
    for frame in range(len(pos)):
        data.qpos[:3], data.qpos[3:7] = pos[frame], quat[frame]
        data.qpos[addresses] = joints[frame]
        mujoco.mj_kinematics(model, data)
        for side, ids in enumerate(feet):
            rotation = data.geom_xmat[ids].reshape(-1, 3, 3)
            radius, half = model.geom_size[ids, 0], model.geom_size[ids, 1]
            result[frame, side] = np.min(data.geom_xpos[ids, 2] - np.abs(rotation[:, 2, 2]) * half - radius)
    return result


def windows(length: int, maximum: int, minimum: int):
    if length < minimum:
        return []
    result = [(start, min(start + maximum, length)) for start in range(0, length, maximum)
              if min(maximum, length - start) >= minimum]
    # Keep the released stop at the end even if the last remainder is short.
    if result[-1][1] < length:
        result.append((max(0, length - maximum), length))
    return result


def quantiles(array):
    return {str(q): float(np.quantile(array, q)) for q in (0, .01, .05, .5, .95, 1)}


def build(args):
    source, out = args.instinct_mj.resolve(), args.output.resolve()
    if out.exists() and any(out.iterdir()):
        raise FileExistsError(f"Refusing to replace an existing dataset: {out}")
    archive = args.archive.resolve() if args.archive else out.parent / "raw" / ASSET_NAME
    fetch_archive(archive)
    if args.license_file:
        license_bytes = args.license_file.read_bytes()
    else:
        with urllib.request.urlopen(LICENSE_URL, timeout=60) as response:
            license_bytes = response.read()
    xml, model, names, controlled, feet = make_model(source)
    maximum, minimum = round(args.window_seconds * 50), round(args.minimum_seconds * 50)
    if not 4 <= args.minimum_seconds <= args.window_seconds <= 6:
        raise ValueError("Use continuous windows between four and six seconds")
    out.mkdir(parents=True, exist_ok=True)
    (out / "motions").mkdir()
    (out / "terrains").mkdir()
    (out / "provenance").mkdir()
    (out / "provenance/PHP_SOURCE_LICENSE").write_bytes(license_bytes)
    write_floor(out / "terrains/flat.stl")
    (out / "terrains/flat.geoms.yaml").write_text(yaml.safe_dump([
        {"type": "box", "pos": [0.0, 0.0, -0.05], "quat": [1.0, 0.0, 0.0, 0.0],
         "size": [14.5, 9.0, 0.05]}], sort_keys=False), encoding="utf-8")
    entries, evidence, excluded = [], [], []
    with tarfile.open(archive, "r:gz") as tar:
        members = {m.name: m for m in tar.getmembers()}
        read = lambda name: tar.extractfile(members[name]).read()
        (out / "provenance/PHP_BUNDLE_README.md").write_bytes(read("README.md"))
        for source_name in sorted(n for n in members if n.endswith("_motion.npz")):
            terrain_name = source_name.removesuffix("_motion.npz") + "_terrain.npy"
            if terrain_name not in members:
                raise ValueError(f"Missing paired terrain for {source_name}")
            terrain_bytes = read(terrain_name)
            terrain = np.load(io.BytesIO(terrain_bytes), allow_pickle=False)
            if terrain.ndim != 3 or terrain.shape[-1] != 10:
                raise ValueError(f"Unexpected paired terrain layout: {terrain_name}")
            if terrain.shape[0] != 0:
                excluded.append({"source_motion": source_name, "source_terrain": terrain_name,
                                 "terrain_sha256": sha(terrain_bytes), "reason": "nonempty released terrain; preserved in source archive"})
                continue
            raw_bytes = read(source_name)
            with np.load(io.BytesIO(raw_bytes), allow_pickle=False) as motion:
                fps = float(motion["fps"].item())
                joints_all = motion["joint_pos"].astype(np.float64)
                source_names = motion["joint_names"].tolist()
                body_names = motion["body_names"].tolist()
                pelvis = body_names.index("pelvis")
                pos = motion["body_pos_w"][:, pelvis].astype(np.float64)
                quat = motion["body_quat_w"][:, pelvis].astype(np.float64)
                if joints_all.shape != (len(pos), 36) or len(source_names) != 29:
                    raise ValueError(f"Expected prepared PHP Holosoma format: {source_name}")
                np.testing.assert_allclose(joints_all[:, :3], pos, rtol=0, atol=1e-8)
                np.testing.assert_allclose(joints_all[:, 3:7], quat, rtol=0, atol=1e-8)
                joints = joints_all[:, 7:][:, [source_names.index(name) for name in names]]
                wrists = joints_all[:, 7:][:, [i for i, n in enumerate(source_names) if "wrist" in n]]
            if not all(np.isfinite(value).all() for value in (pos, quat, joints)):
                raise ValueError(f"Nonfinite motion: {source_name}")
            norms = np.linalg.norm(quat, axis=1)
            if np.max(abs(norms - 1)) > 1e-4:
                raise ValueError(f"Invalid source root quaternion norm: {source_name}")
            quat /= norms[:, None]
            if fps != 50:
                old = np.arange(len(pos)) / fps
                new = np.arange(int(np.floor(old[-1] * 50)) + 1) / 50
                pos = np.stack([np.interp(new, old, pos[:, i]) for i in range(3)], -1)
                joints = np.stack([np.interp(new, old, joints[:, i]) for i in range(23)], -1)
                quat = Slerp(old, Rotation.from_quat(quat[:, [1, 2, 3, 0]]))(new).as_quat()[:, [3, 0, 1, 2]]
            cfg = Path(source_name).name.split("_", 1)[0]
            for index, (start, end) in enumerate(windows(len(pos), maximum, minimum)):
                p, q, j = pos[start:end].copy(), quat[start:end].copy(), joints[start:end].copy()
                center = (p[:, :2].min(0) + p[:, :2].max(0)) / 2
                p[:, :2] -= center
                if np.any(np.max(abs(p[:, :2]), axis=0) > [13.5, 8.0]):
                    excluded.append({"source_motion": source_name, "frames": [start, end], "reason": "root trajectory exceeds tile with one metre robot margin"})
                    continue
                before = foot_height(model, controlled, feet, p, q, j)
                offset = -float(np.quantile(before.min(axis=1), args.height_quantile))
                if abs(offset) > args.max_height_shift:
                    excluded.append({"source_motion": source_name, "frames": [start, end], "reason": "required constant height shift exceeds bound", "z_offset": offset})
                    continue
                p[:, 2] += offset
                after = before + offset
                if after.min() < -args.max_penetration:
                    excluded.append({"source_motion": source_name, "frames": [start, end], "reason": "foot penetration exceeds bound after constant height shift", "min_height": float(after.min())})
                    continue
                rel = f"motions/php_{cfg}_{index:02d}.npz"
                np.savez_compressed(out / rel, framerate=np.array(50), joint_names=np.array(names),
                                    joint_pos=j.astype(np.float32), base_pos_w=p.astype(np.float32), base_quat_w=q.astype(np.float32))
                speed = np.linalg.norm(np.gradient(p[:, :2], .02, axis=0), axis=1)
                yaw = np.unwrap(Rotation.from_quat(q[:, [1, 2, 3, 0]]).as_euler("xyz")[:, 2])
                entries.append({"motion_file": rel, "terrain_id": 0, "group": "walk__php_examples", "weight": 1.0})
                evidence.append({"motion_file": rel, "sha256": file_sha(out / rel), "source_motion": source_name,
                                 "source_motion_sha256": sha(raw_bytes), "source_terrain": terrain_name,
                                 "source_terrain_sha256": sha(terrain_bytes), "source_terrain_shape": list(terrain.shape),
                                 "source_framerate": fps, "output_framerate": 50, "output_source_grid_frames": [start, end],
                                 "source_time_seconds": [start / 50, (end - 1) / 50], "frames": end - start,
                                 "xy_translation": (-center).tolist(), "z_translation": offset,
                                 "foot_height_before": quantiles(before.min(axis=1)), "foot_height_after": quantiles(after.min(axis=1)),
                                 "root_speed_xy": quantiles(speed), "stationary_frame_fraction_speed_lt_0.1": float(np.mean(speed < .1)),
                                 "yaw_change_radians": float(yaw[-1] - yaw[0]), "discarded_wrist_peak_abs": np.max(abs(wrists), axis=0).tolist()})
    if not entries:
        raise ValueError("No released flat-ground windows passed geometry checks")
    # Split ORIGINAL source-file content hashes, never overlapping windows.
    # Byte-identical source files remain in the same split even if renamed.
    source_hashes = sorted({item["source_motion_sha256"] for item in evidence})
    holdout_count = max(1, round(len(source_hashes) * args.holdout_fraction))
    if holdout_count >= len(source_hashes):
        raise ValueError("At least one distinct training source and one holdout source are required")
    holdout_hashes = set(source_hashes[-holdout_count:])
    split_by_file = {}
    for item in evidence:
        item["split"] = "holdout" if item["source_motion_sha256"] in holdout_hashes else "train"
        split_by_file[item["motion_file"]] = item["split"]
    metadata = {"label": "PHP locomotion example release: ACP flat subset, continuous real frames",
                "base_link": "pelvis", "motion_files": entries,
                "terrains": [{"terrain_id": 0, "terrain_file": "terrains/flat.stl", "terrain_geoms": "terrains/flat.geoms.yaml"}]}
    (out / "metadata.all.yaml").write_text(yaml.safe_dump(metadata, sort_keys=False), encoding="utf-8")
    train_metadata = {**metadata, "motion_files": [entry for entry in entries if split_by_file[entry["motion_file"]] == "train"]}
    (out / "metadata.yaml").write_text(yaml.safe_dump(train_metadata, sort_keys=False), encoding="utf-8")
    for name, selected in (("holdout", [entry for entry in entries if split_by_file[entry["motion_file"]] == "holdout"]), ("all", entries)):
        (out / name).mkdir()
        relative_metadata = {**metadata,
                             "motion_files": [{**entry, "motion_file": "../" + entry["motion_file"]} for entry in selected],
                             "terrains": [{**terrain, "terrain_file": "../" + terrain["terrain_file"],
                                           "terrain_geoms": "../" + terrain["terrain_geoms"]} for terrain in metadata["terrains"]]}
        (out / name / "metadata.yaml").write_text(yaml.safe_dump(relative_metadata, sort_keys=False), encoding="utf-8")
    commit = subprocess.check_output(["git", "-C", str(source), "rev-parse", "HEAD"], text=True).strip()
    provenance = {"schema_version": 1, "release_url": RELEASE_URL, "source_commit": SOURCE_COMMIT,
                  "archive": str(archive), "archive_url": ASSET_URL, "archive_sha256": ASSET_SHA256,
                  "source_license_url": LICENSE_URL, "source_license_sha256": sha(license_bytes),
                  "source_notice": "This is a subset of example training inputs, not the complete PHP parkour dataset or pretrained policies.",
                  "conversion": "Named 29-to-23 joint selection; pelvis xyz/wxyz; preserve 50Hz frames (linear position/joint interpolation and quaternion Slerp only if needed); continuous windows; constant xy recenter and per-window z translation only; no joint clipping, no synthetic stopping frames.",
                  "height_alignment": {"quantile": args.height_quantile, "max_absolute_z_shift": args.max_height_shift, "max_foot_penetration": args.max_penetration},
                  "contact_labels": "not synthesized; run the actual ACP label_contacts module with --simplified-collision",
                  "acp_asset": {"xml": str(xml), "xml_sha256": file_sha(xml), "git_commit": commit, "mujoco_version": mujoco.__version__, "joint_names": names},
                  "split": {"method": "sort unique original motion-file SHA256 values; last 20 percent holdout; same hash always same split",
                            "holdout_fraction": args.holdout_fraction, "train_source_hashes": [value for value in source_hashes if value not in holdout_hashes],
                            "holdout_source_hashes": sorted(holdout_hashes),
                            "training_metadata": "metadata.yaml", "holdout_metadata": "holdout/metadata.yaml",
                            "label_all_dataset": "all/metadata.yaml", "all_metadata": "metadata.all.yaml"},
                  "selected_windows": evidence, "excluded": excluded,
                  "summary": {"source_pairs": 100, "selected_source_motions": len(set(x["source_motion"] for x in evidence)),
                              "windows": len(entries), "frames": sum(x["frames"] for x in evidence),
                              "train_sources": len(source_hashes) - holdout_count, "holdout_sources": holdout_count,
                              "train_windows": len(train_metadata["motion_files"]),
                              "holdout_windows": len(entries) - len(train_metadata["motion_files"])}}
    (out / "provenance.json").write_text(json.dumps(provenance, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"output": str(out), **provenance["summary"], "metadata_sha256": file_sha(out / "metadata.yaml")}, indent=2))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--instinct-mj", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--archive", type=Path, help="Pinned original archive; downloaded if absent")
    parser.add_argument("--license-file", type=Path, help="Use a saved copy of the pinned source LICENSE for offline conversion")
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--window-seconds", type=float, default=6.0)
    parser.add_argument("--minimum-seconds", type=float, default=4.0)
    parser.add_argument("--height-quantile", type=float, default=.05)
    parser.add_argument("--max-height-shift", type=float, default=.05)
    parser.add_argument("--max-penetration", type=float, default=.03)
    parser.add_argument("--holdout-fraction", type=float, default=.2)
    args = parser.parse_args()
    if not 0 <= args.height_quantile <= 1:
        parser.error("height-quantile must lie in [0,1]")
    if not 0 < args.holdout_fraction < 1:
        parser.error("holdout-fraction must lie in (0,1)")
    build(args)


if __name__ == "__main__":
    main()
